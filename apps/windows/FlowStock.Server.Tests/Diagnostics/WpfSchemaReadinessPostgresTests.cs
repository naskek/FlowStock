using FlowStock.Data;
using FlowStock.Server.Tests.Support;
using Npgsql;

namespace FlowStock.Server.Tests.Diagnostics;

[Collection(PostgresLocationIntegrationTestCollection.Name)]
public sealed class WpfSchemaReadinessPostgresTests
{
    [Fact]
    public void Initialize_CurrentMigratedSchema_ReadOnlySessionSucceeds()
    {
        var baseConnectionString = Environment.GetEnvironmentVariable("FLOWSTOCK_POSTGRES_TEST_CONNECTION");
        if (string.IsNullOrWhiteSpace(baseConnectionString))
        {
            return;
        }

        var readOnly = BuildReadOnlyConnectionString(baseConnectionString, null);
        new PostgresDataStore(readOnly).Initialize();
    }

    [Theory]
    [InlineData("missing_table", "Missing table 'items'")]
    [InlineData("missing_column", "Missing column 'item_types.enable_marking'")]
    [InlineData("missing_constraint", "Missing constraint 'ck_orders_terminal_partial_outbound_false'")]
    [InlineData("nonnullable_order_id", "'marking_order.order_id' must be nullable")]
    [InlineData("empty_migrations", "no applied migrations")]
    public void Initialize_IncompleteSchema_ReadOnlySessionFailsClosed(string scenario, string expectedMessage)
    {
        var baseConnectionString = Environment.GetEnvironmentVariable("FLOWSTOCK_POSTGRES_TEST_CONNECTION");
        if (string.IsNullOrWhiteSpace(baseConnectionString))
        {
            return;
        }

        // Only the dedicated migrated test database may receive the disposable fixture.
        var builder = new NpgsqlConnectionStringBuilder(baseConnectionString);
        Assert.EndsWith("_test", builder.Database, StringComparison.OrdinalIgnoreCase);

        var schema = "wpf_schema_" + Guid.NewGuid().ToString("N");
        using var admin = new NpgsqlConnection(baseConnectionString);
        admin.Open();
        try
        {
            RunSql(admin, $"CREATE SCHEMA \"{schema}\";");
            foreach (var table in RequiredFixtureTables)
            {
                RunSql(admin, $"CREATE TABLE \"{schema}\".\"{table}\" (LIKE public.\"{table}\" INCLUDING CONSTRAINTS);");
            }

            RunSql(admin, $"INSERT INTO \"{schema}\".schema_migrations (version, filename, applied_at) VALUES ('V0001', 'fixture.sql', NOW());");
            switch (scenario)
            {
                case "missing_table":
                    RunSql(admin, $"DROP TABLE \"{schema}\".items;");
                    break;
                case "missing_column":
                    RunSql(admin, $"ALTER TABLE \"{schema}\".item_types DROP COLUMN enable_marking;");
                    break;
                case "missing_constraint":
                    RunSql(admin, $"ALTER TABLE \"{schema}\".orders DROP CONSTRAINT ck_orders_terminal_partial_outbound_false;");
                    break;
                case "nonnullable_order_id":
                    RunSql(admin, $"ALTER TABLE \"{schema}\".marking_order ALTER COLUMN order_id SET NOT NULL;");
                    break;
                case "empty_migrations":
                    RunSql(admin, $"TRUNCATE TABLE \"{schema}\".schema_migrations;");
                    break;
                default:
                    throw new ArgumentOutOfRangeException(nameof(scenario));
            }

            var readOnly = BuildReadOnlyConnectionString(baseConnectionString, schema);
            var error = Assert.Throws<InvalidOperationException>(() => new PostgresDataStore(readOnly).Initialize());
            Assert.Contains(expectedMessage, error.Message, StringComparison.OrdinalIgnoreCase);
            Assert.Contains("migrate.sh", error.Message, StringComparison.Ordinal);
        }
        finally
        {
            // The schema name is generated by this test and is never shared with application data.
            RunSql(admin, $"DROP SCHEMA IF EXISTS \"{schema}\" CASCADE;");
        }
    }

    private static string BuildReadOnlyConnectionString(string connectionString, string? schema)
    {
        var builder = new NpgsqlConnectionStringBuilder(connectionString)
        {
            Pooling = false,
            Options = "-c default_transaction_read_only=on"
        };
        if (schema != null)
        {
            builder.SearchPath = schema;
        }
        return builder.ConnectionString;
    }

    private static void RunSql(NpgsqlConnection connection, string sql)
    {
        using var command = new NpgsqlCommand(sql, connection);
        command.ExecuteNonQuery();
    }

    private static readonly string[] RequiredFixtureTables =
    [
        "schema_migrations",
        "items", "item_types", "vat_rates", "partner_item_sale_prices",
        "write_off_reasons", "orders", "order_lines", "order_receipt_plan_lines",
        "docs", "doc_lines", "production_pallets", "production_pallet_lines",
        "ledger", "tsd_devices", "marking_order", "marking_code", "client_blocks",
        "warehouse_action_bundles", "warehouse_action_lines", "warehouse_tasks",
        "warehouse_task_lines", "warehouse_task_events", "locations"
    ];
}
